  // Helper methods

  static int _findColumnIndex(List<String> headers, List<String> possibleNames) {
    for (int i = 0; i < headers.length; i++) {
      final header = headers[i].replaceAll(' ', '').replaceAll('_', '').toLowerCase();
      for (final name in possibleNames) {
        if (header.contains(name.replaceAll(' ', ''))) {
          return i;
        }
      }
    }
    return -1;
  }

  static String? _getCell(List row, int index) {
    if (index < 0 || index >= row.length) return null;
    final value = row[index]?.toString();
    return value?.isEmpty == true ? null : value;
  }

  static bool _isValidEmail(String email) {
    return RegExp(r'^[\w-\.]+@([\w-]+\.)+[\w-]{2,4}$').hasMatch(email);
  }
}
